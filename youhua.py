import numpy as np

def calculate_calibration_coefficients():
    # ==========================================
    # 1. 数据输入区 (请替换为你实际测得的已知数据)
    # ==========================================
    
    # 输入主方向弹性模量 (单位：MPa)
    Ex = 195000.0  
    Ey = 8580.0    
    
    # 输入你已知的 x 方向残余应力 (单位：MPa)
    sigma_x = 50  # 这里的数字仅为演示，请填入你自己的应力值
    
    # 输入三个方向测得的应变值 
    e1 = 13.5*10**-6
    e2 = 14.0*10**-6
    e3 = 18.7*10**-6

    # ==========================================
    # 2. 核心计算区
    # ==========================================
    
    # 计算公式中的弹性模量平方根项
    sqrt_E = np.sqrt(Ex * Ey)
    
    # 根据反推公式计算 C11, C21, C31
    C11 = (e1 * sqrt_E) / sigma_x
    C21 = (e2 * sqrt_E) / sigma_x
    C31 = (e3 * sqrt_E) / sigma_x

    # ==========================================
    # 3. 结果输出区
    # ==========================================
    print("=" * 45)
    print("           矩阵系数 C 反推求值结果")
    print("=" * 45)
    print(f"已知弹性模量 : Ex = {Ex} MPa, Ey = {Ey} MPa")
    print(f"已知输入应力 : sigma_x = {sigma_x} MPa")
    print("-" * 45)
    print(f"求得 C11 : {C11:>12.6f}")
    print(f"求得 C21 : {C21:>12.6f}")
    print(f"求得 C31 : {C31:>12.6f}")
    print("=" * 45)

if __name__ == "__main__":
    calculate_calibration_coefficients()